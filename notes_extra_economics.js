<h4>5. <strong>Employment: Definitions and Classifications</strong></h4>
<ul>
  <li><strong>Employment</strong> – Persons engaged in any economic activity for at least one hour during the reference week (as per <strong>PLFS</strong> methodology).</li>
  <li><strong>Unemployment</strong> – Individuals without work, available for work, and seeking employment.</li>
  <li><strong>Under‑employment</strong> – Workers employed for fewer hours than desired (common in agriculture).</li>
