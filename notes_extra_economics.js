<h4>4. <strong>Determinants of Poverty in Rural India</strong></h4>
<ul>
  <li><strong>Landlessness</strong> – Approximately 25 % of rural households are land‑less, relying on wage labour.</li>
  <li><strong>Fragmented Holdings</strong> – Average operational land per household is 1.15 ha (2015‑16), limiting economies of scale.</li>
