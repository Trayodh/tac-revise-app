  <p>Ecology (<em>Greek: oikos</em> = house, <em>logos</em> = study) is the scientific study of interactions among organisms and their abiotic and biotic environment. The term was coined by <strong>Ernst Haeckel</strong> in 1866. Ecology examines patterns of distribution, abundance, and the processes that drive them, ranging from individual physiology to the functioning of the entire <strong>biosphere</strong> ([[Biosphere]]).</p>

