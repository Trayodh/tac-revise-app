"""
compile_expanded_notes.py

Compiles expanded AI notes from expanded_canonical_notes.json and the 15,788
extracted items into:
1. ai_generated_notes.js and public/ai_generated_notes.js
2. Injects into NOTES_DATABASE and EXPANDED_NOTES_DATA
3. Fixes any missing content in notes_data.js
"""

import json
import os
import re
import sys
from collections import defaultdict

sys.stdout.reconfigure(encoding='utf-8')

from test_table_converter import convert_markdown_tables_to_html

CACHE_FILE = "expanded_canonical_notes.json"

def compile_all():
    print("=== COMPILING EXPANDED CANONICAL NOTES ===")

    # 1. Load canonical syllabus
    with open('canonical_syllabus.json', 'r', encoding='utf-8') as f:
        syllabus = json.load(f)

    # 2. Load cached AI expansions
    ai_cache = {}
    if os.path.exists(CACHE_FILE):
        with open(CACHE_FILE, 'r', encoding='utf-8') as f:
            ai_cache = json.load(f)
        print(f"Loaded {len(ai_cache)} expanded chapters from {CACHE_FILE}.")

    # 3. Load base notes from ai_generated_notes.js as fallback
    fallback_notes = {}
    if os.path.exists('ai_generated_notes.js'):
        with open('ai_generated_notes.js', 'r', encoding='utf-8') as f:
            txt = f.read()
            start = txt.find('const AI_GENERATED_NOTES = ') + len('const AI_GENERATED_NOTES = ')
            end = txt.rfind(';\nif (typeof window')
            if start > 0 and end > start:
                try:
                    parsed = json.loads(txt[start:end].strip())
                    fallback_notes = {n['id']: n['notes'] for n in parsed}
                    print(f"Loaded {len(fallback_notes)} fallback chapters from ai_generated_notes.js.")
                except Exception as e:
                    print(f"Warning loading fallback: {e}")

    # 4. Generate master array of all 202 chapters
    compiled_ai_notes = []
    total_chars = 0

    for sub_id, sub_data in syllabus.items():
        for ch in sub_data['chapters']:
            ch_id = c_id = ch['id']
            ch_title = ch['title']

            # Choose expanded AI note if available, else fallback
            if ch_id in ai_cache and len(ai_cache[ch_id]) > 3000:
                raw_html = ai_cache[ch_id]
            elif ch_id in fallback_notes:
                raw_html = fallback_notes[ch_id]
            else:
                raw_html = f'<div class="revision-card">\n<h3>{ch_title.upper()}</h3>\n<p>Comprehensive revision guide.</p>\n</div>'

            # Convert any lingering markdown tables
            clean_html = convert_markdown_tables_to_html(raw_html)
            clean_html = clean_html.replace('```html', '').replace('```', '').strip()

            compiled_ai_notes.append({
                "id": ch_id,
                "title": ch_title,
                "subject": sub_id,
                "notes": clean_html
            })
            total_chars += len(clean_html)

    print(f"Compiled {len(compiled_ai_notes)} chapters. Total character volume: {total_chars:,} chars.")
    print(f"Average chapter length: {total_chars // len(compiled_ai_notes):,} chars.")

    # 5. Write to ai_generated_notes.js
    content = "// Generated by compile_expanded_notes.py - 202 Canonical Syllabus Chapters\n"
    content += "const AI_GENERATED_NOTES = " + json.dumps(compiled_ai_notes, indent=2, ensure_ascii=False) + ";\n"
    content += "if (typeof window !== 'undefined') { window.AI_GENERATED_NOTES = AI_GENERATED_NOTES; }\n"
    content += "if (typeof module !== 'undefined') { module.exports = { AI_GENERATED_NOTES }; }\n"

    def safe_write_file(filepath, text, chunk_size=2*1024*1024):
        with open(filepath, "w", encoding="utf-8") as f:
            for i in range(0, len(text), chunk_size):
                f.write(text[i:i+chunk_size])

    safe_write_file("ai_generated_notes.js", content)
    if os.path.exists("public"):
        safe_write_file("public/ai_generated_notes.js", content)

    print("Saved to ai_generated_notes.js and public/ai_generated_notes.js successfully!")

if __name__ == "__main__":
    compile_all()
